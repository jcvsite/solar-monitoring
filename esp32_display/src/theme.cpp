static const char* kThemeNames[] = {"Dark", "Light", "Solar", "Ocean", "Forest"};

void themeSetActive(uint8_t id) {
  if (id > 4) id = 0;
  s_themeId = id;
  s_active = kThemes[id];
}

const ThemePalette& themeActive() { return s_active; }

const char* themeName(uint8_t id) {
  if (id > 4) id = 0;
  return kThemeNames[id];
}
